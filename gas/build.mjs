// Builds the Google Apps Script version into two copy-paste files:
//   gas/dist/Code.gs     – all of gas/server/*.js
//   gas/dist/Index.html  – the web UI (public/) with CSS and JS inlined
// Usage: node gas/build.mjs
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const pub = join(root, 'public');
const dist = join(here, 'dist');
mkdirSync(dist, { recursive: true });

// ---------- Code.gs ----------
const serverDir = join(here, 'server');
const banner = `// UPSIHub – Google Apps Script edition. Generated by gas/build.mjs; edit gas/server/*.js instead.\n`;
const code = banner + readdirSync(serverDir).filter((f) => f.endsWith('.js')).sort()
  .map((f) => `\n// ===== ${f} =====\n` + readFileSync(join(serverDir, f), 'utf8')).join('');
writeFileSync(join(dist, 'Code.gs'), code);

// ---------- Index.html ----------
// A tiny ES-module bundler for our own code: every module becomes a function scope that
// returns its exports, evaluated in dependency order (the import graph has no cycles).
const order = [];
const seen = new Set();
const IMPORT_RE = /^import\s+(?:([\s\S]*?)\s+from\s+)?['"](.+?)['"];?[ \t]*$/gm;
function visit(file, stack = []) {
  if (seen.has(file)) return;
  if (stack.includes(file)) throw new Error(`Import cycle: ${[...stack, file].join(' → ')}`);
  const src = readFileSync(file, 'utf8');
  for (const m of src.matchAll(IMPORT_RE)) visit(resolve(dirname(file), m[2]), [...stack, file]);
  seen.add(file);
  order.push(file);
}
const id = (file) => relative(pub, file).replace(/\\/g, '/');
function transform(file) {
  let src = readFileSync(file, 'utf8');
  const names = [];
  src = src.replace(IMPORT_RE, (_, spec, from) => {
    const dep = JSON.stringify(id(resolve(dirname(file), from)));
    if (!spec) return '';
    const inner = spec.trim().match(/^\{([\s\S]*)\}$/);
    if (!inner) throw new Error(`${id(file)}: only named imports are supported`);
    const binds = inner[1].split(',').map((s) => s.trim()).filter(Boolean).map((s) => s.replace(/\s+as\s+/, ': '));
    return `const { ${binds.join(', ')} } = __m[${dep}];`;
  });
  src = src.replace(/^export\s*\{([^}]*)\};?[ \t]*$/gm, (_, list) => {
    list.split(',').map((s) => s.trim()).filter(Boolean).forEach((n) => names.push(n));
    return '';
  });
  src = src.replace(/^export\s+((?:async\s+)?function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm, (_, kw, name) => {
    names.push(name);
    return `${kw} ${name}`;
  });
  if (/^export\s/m.test(src)) throw new Error(`${id(file)}: unsupported export form`);
  return `__m[${JSON.stringify(id(file))}] = (function () {\n'use strict';\n${src}\nreturn { ${[...new Set(names)].join(', ')} };\n})();\n`;
}
visit(join(pub, 'js', 'app.js'));
const bundle = 'const __m = {};\n' + order.map(transform).join('\n');
const safe = (s) => s.replace(/<\/(script|style)/gi, '<\\/$1');

let html = readFileSync(join(pub, 'index.html'), 'utf8');
const css = readFileSync(join(pub, 'css', 'app.css'), 'utf8');
const theme = readFileSync(join(pub, 'js', 'theme.js'), 'utf8');
const replaceOnce = (needle, value) => {
  if (!html.includes(needle)) throw new Error(`index.html: missing ${needle}`);
  html = html.replace(needle, () => value);
};
replaceOnce('  <link rel="icon" href="/icon.svg" type="image/svg+xml">\n', '');
replaceOnce('  <link rel="manifest" href="/manifest.webmanifest">\n', '');
replaceOnce('<link rel="stylesheet" href="/css/app.css">', `<base target="_self">\n  <style>\n${safe(css)}\n  </style>`);
replaceOnce('<script src="/js/theme.js"></script>', `<script>\n${safe(theme)}\n</script>`);
replaceOnce('<script type="module" src="/js/app.js"></script>', `<script>\n(function () {\n${safe(bundle)}\n})();\n</script>`);
writeFileSync(join(dist, 'Index.html'), `<!-- UPSIHub – generated by gas/build.mjs; edit public/ instead. -->\n` + html);

writeFileSync(join(dist, 'appsscript.json'), JSON.stringify({
  timeZone: 'Asia/Kuala_Lumpur',
  exceptionLogging: 'STACKDRIVER',
  runtimeVersion: 'V8',
  webapp: { executeAs: 'USER_DEPLOYING', access: 'ANYONE_ANONYMOUS' }
}, null, 2) + '\n');

const kb = (s) => `${(Buffer.byteLength(s) / 1024).toFixed(0)} KB`;
console.log(`gas/dist/Code.gs     ${kb(code)}\ngas/dist/Index.html  ${kb(html)} (${order.length} modules)`);
